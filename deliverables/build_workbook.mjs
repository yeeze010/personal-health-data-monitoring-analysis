function col(n) {
  let s = "";
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

function sheetWithData(name, values, widths = []) {
  const sheet = workbook.worksheets.getOrAdd(name, { renameFirstIfOnlyNewSpreadsheet: true });
  const rows = values.length;
  const cols = values[0].length;
  const range = sheet.getRange(`A1:${col(cols)}${rows}`);
  range.values = values;
  range.format = {
    font: { name: "Microsoft YaHei", size: 10, color: "#111827" },
    verticalAlignment: "center",
    wrapText: true,
    borders: { preset: "all", style: "thin", color: "#D1D5DB" },
  };
  sheet.getRange(`A1:${col(cols)}1`).format = {
    fill: "#1F4D78",
    font: { name: "Microsoft YaHei", size: 10, color: "#FFFFFF", bold: true },
    horizontalAlignment: "center",
    verticalAlignment: "center",
    wrapText: true,
    borders: { preset: "all", style: "thin", color: "#D1D5DB" },
  };
  for (let i = 0; i < widths.length; i += 1) {
    sheet.getRange(`${col(i + 1)}1:${col(i + 1)}${rows}`).format.columnWidthPx = widths[i];
  }
  return sheet;
}

